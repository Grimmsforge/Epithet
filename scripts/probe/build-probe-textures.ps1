<#
.SYNOPSIS
    Regenerates the probe's texture list from Epithet's source.

.DESCRIPTION
    Scans Core/, UI/, Spotting/ and Flavors/ (Lua and XML) for every Blizzard
    texture path Epithet names (Interface\..., excluding Epithet's own
    Interface\AddOns\Epithet\ files, which ship with the addon) and writes them
    to tools/probe/EpithetProbe/Textures.lua with the file and line that uses
    each. The probe then tries every path on a live client, so the list can
    never drift from what Epithet actually loads.

    Paths built at runtime (the Logbook's race icon candidates end in "_" or "-"
    and get a race token appended) cannot be listed; they are reported here and
    skipped. The Logbook already falls back through its own candidates for them.

.EXAMPLE
    powershell -File scripts\probe\build-probe-textures.ps1
#>

[CmdletBinding()]
param(
    [string]$RepoRoot
)

$ErrorActionPreference = 'Stop'
if (-not $RepoRoot) { $RepoRoot = Join-Path $PSScriptRoot '..\..' }
$RepoRoot = (Resolve-Path $RepoRoot).Path
$outFile = Join-Path $RepoRoot 'tools\probe\EpithetProbe\Textures.lua'

$found = [ordered]@{}
$dynamic = [System.Collections.Generic.List[string]]::new()

foreach ($dir in @('Core', 'UI', 'Spotting', 'Flavors')) {
    $p = Join-Path $RepoRoot $dir
    if (-not (Test-Path $p)) { continue }
    foreach ($file in Get-ChildItem -LiteralPath $p -Recurse -File -Include '*.lua', '*.xml') {
        if ($file.Name -like '*.local.lua') { continue }
        $rel = $file.FullName.Substring($RepoRoot.Length + 1)
        $isXml = $file.Extension -eq '.xml'
        $n = 0
        foreach ($line in Get-Content -LiteralPath $file.FullName) {
            $n++
            if ($line -match '^\s*--') { continue }
            $matches_ = if ($isXml) {
                [regex]::Matches($line, 'file="(Interface\\[^"]+)"') | ForEach-Object { $_.Groups[1].Value }
            } else {
                # Lua source spells each backslash as "\\".
                [regex]::Matches($line, '["''](Interface\\\\[^"'']+)["'']') | ForEach-Object { $_.Groups[1].Value -replace '\\\\', '\' }
            }
            foreach ($path in $matches_) {
                if ($path -match '^Interface\\AddOns\\') { continue }
                if ($path -match '[_\-]$') { $dynamic.Add("${rel}:$n  $path<token>"); continue }
                $key = $path.ToLowerInvariant()
                if (-not $found.Contains($key)) { $found[$key] = @{ path = $path; used = "${rel}:$n" } }
            }
        }
    }
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('-- GENERATED by scripts/probe/build-probe-textures.ps1 - do not edit.')
[void]$sb.AppendLine('-- Every Blizzard texture Epithet names, with the first place that uses it.')
[void]$sb.AppendLine('EpithetProbeTextures = {')
foreach ($entry in $found.Values) {
    $luaPath = $entry.path -replace '\\', '\\'
    $luaUsed = $entry.used -replace '\\', '/'
    [void]$sb.AppendLine("    { path = `"$luaPath`", used = `"$luaUsed`" },")
}
[void]$sb.AppendLine('}')
New-Item -ItemType Directory -Force (Split-Path $outFile) | Out-Null
[System.IO.File]::WriteAllText($outFile, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))

Write-Host "Wrote $($found.Count) texture paths to $outFile" -ForegroundColor Green
if ($dynamic.Count -gt 0) {
    Write-Host "Skipped $($dynamic.Count) runtime-built path prefix(es):" -ForegroundColor DarkGray
    $dynamic | Select-Object -Unique | ForEach-Object { Write-Host "  $_" -ForegroundColor DarkGray }
}
